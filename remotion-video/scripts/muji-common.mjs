export function mergeVocab(extra = []) {
  const seen = new Set();
  return [...COMMON_VOCAB, ...extra].filter((entry) => {
    if (seen.has(entry.surface)) return false;
    seen.add(entry.surface);
    return true;
  });
}

export function buildComments(topic) {
  if (!Array.isArray(topic.body) || topic.body.length !== 50) {
    throw new Error(`${topic.slug}: body must contain exactly 50 comments, got ${topic.body?.length ?? 0}`);
  }

  const comments = [
    {
      id: 0,
      ...INTRO_SPEAKER,
      image: 'title.png',
      seFile: '和太鼓でドドン.mp3',
      isIntro: true,
      text: topic.intro[0],
    },
    {
      id: 1,
      ...INTRO_SPEAKER,
      image: 'title.png',
      seFile: '拍子木1.mp3',
      isIntro: true,
      text: topic.intro[1],
    },
    {
      id: 2,
      ...INTRO_SPEAKER,
      image: 'title.png',
      seFile: '拍子木2.mp3',
      isIntro: true,
      text: 'それではどうぞ！',
    },
  ];

  topic.body.forEach((text, index) => {
    const id = index + 3;
    const speaker = MAIN_SPEAKERS[index % MAIN_SPEAKERS.length];
    comments.push({
      id,
      ...speaker,
      image: `anime_${String(Math.floor(index / 4) + 1).padStart(2, '0')}.png`,
      ...(index % 4 === 0 ? { seFile: MAIN_SE[Math.floor(index / 4) % MAIN_SE.length] } : {}),
      text,
    });
  });

  return comments;
}

export function buildTopicScript(topic) {
  return {
    VOCAB: mergeVocab(topic.vocab),
    COMMENTS: buildComments(topic),
  };
}
